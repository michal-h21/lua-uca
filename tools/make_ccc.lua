-- make the table of canonical combining classes other than 0 from
-- UnicodeData.txt, used for discontiguous contractions (UTS #10, S2.1.1)
local dir = arg[1] or "data"

local ccc = {}
for line in io.lines(dir .. "/UnicodeData.txt") do
  local codepoint, class = line:match("^(%x+);[^;]*;[^;]*;(%d+);")
  if codepoint and class ~= "0" then
    ccc[#ccc + 1] = {tonumber(codepoint, 16), class}
  end
end

local out = {}
for i, entry in ipairs(ccc) do
  out[#out + 1] = string.format("[0x%X]=%s,", entry[1], entry[2])
  if i % 4 == 0 then out[#out + 1] = "\n  " else out[#out + 1] = " " end
end

print("-- generated by tools/make_ccc.lua")
print("-- canonical combining classes other than 0")
print("return {")
print("  " .. (table.concat(out):gsub("%s*$", "")))
print("}")
