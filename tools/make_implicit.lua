-- make the table of ranges for implicit weights (UTS #10, section 10.1.3)
-- from allkeys.txt (the @implicitweights lines), PropList.txt
-- (Unified_Ideograph) and Blocks.txt
local dir = arg[1] or "data"

local function read_ranges(filename, fn)
  for line in io.lines(dir .. "/" .. filename) do
    local first, last, rest = line:match("^(%x+)%.?%.?(%x*)%s*;%s*(.-)%s*$")
    if first then
      first = tonumber(first, 16)
      last = last ~= "" and tonumber(last, 16) or first
      fn(first, last, rest)
    end
  end
end

-- siniform ideographic scripts: the BBBB weight is counted from the first
-- code point of the first range with the same AAAA weight
local blocks, origins = {}, {}
for line in io.lines(dir .. "/allkeys.txt") do
  local first, last, base = line:match("^@implicitweights%s+(%x+)%.%.(%x+)%s*;%s*(%x+)")
  if first then
    first, last, base = tonumber(first, 16), tonumber(last, 16), tonumber(base, 16)
    origins[base] = origins[base] or first
    blocks[#blocks + 1] = {first, last, base, origins[base]}
  end
end

-- core Han: Unified_Ideograph in the CJK Unified Ideographs or
-- CJK Compatibility Ideographs blocks
local core_blocks = {}
read_ranges("Blocks.txt", function(first, last, name)
  if name == "CJK Unified Ideographs" or name == "CJK Compatibility Ideographs" then
    core_blocks[#core_blocks + 1] = {first, last}
  end
end)

local function is_core(first, last)
  for _, block in ipairs(core_blocks) do
    if first >= block[1] and last <= block[2] then return true end
    -- PropList.txt ranges do not cross block boundaries, check it anyway
    assert(last < block[1] or first > block[2], "range crosses a core Han block")
  end
  return false
end

local core_han, other_han = {}, {}
read_ranges("PropList.txt", function(first, last, prop)
  if prop:match("^Unified_Ideograph%f[%s#]") or prop == "Unified_Ideograph" then
    local t = is_core(first, last) and core_han or other_han
    t[#t + 1] = {first, last}
  end
end)

local function sort(t) table.sort(t, function(a, b) return a[1] < b[1] end) end
sort(blocks); sort(core_han); sort(other_han)

local function dump(name, t)
  local out = {}
  for _, range in ipairs(t) do
    local values = {}
    for i, x in ipairs(range) do values[i] = string.format("0x%X", x) end
    out[#out + 1] = "  {" .. table.concat(values, ", ") .. "}"
  end
  return name .. " = {\n" .. table.concat(out, ",\n") .. "\n}"
end

local version
for line in io.lines(dir .. "/allkeys.txt") do
  version = line:match("^@version%s+(%S+)")
  if version then break end
end

print("-- generated by tools/make_implicit.lua from the Unicode " .. (version or "") .. " data")
print("-- {first, last, AAAA, origin of BBBB}")
print("local " .. dump("blocks", blocks))
print("local " .. dump("core_han", core_han))
print("local " .. dump("other_han", other_han))
print("return {blocks = blocks, core_han = core_han, other_han = other_han}")
